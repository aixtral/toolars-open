/**
 * Tracked so the error path can close Chromium. Without this the process
 * stays alive on a thrown scenario (an open browser keeps the event loop
 * busy), so a failing run would hang instead of failing loudly.
 */
let activeBrowser = null;

/**
 * Classify a thrown scenario error.
 *
 * A transport failure means the run could not be completed; it says nothing
 * about whether data left the device and must never be reported as if it did.
 * `timeout` is kept separate because it is usually a wait-condition problem.
 */
function classifyScenarioError(error) {
  const message = String(error?.message ?? error);
  const firstLine = message.split("\n")[0].slice(0, 300);
  if (
    /net::ERR_|NS_ERROR_|ERR_CONNECTION|ERR_NAME_NOT_RESOLVED|ERR_INTERNET|socket hang up/iu.test(
      message,
    )
  ) {
    return { errorClass: "transport", reason: firstLine };
  }
  if (/Timeout \d+ms exceeded|waiting until/iu.test(message)) {
    return { errorClass: "timeout", reason: firstLine };
  }
  return { errorClass: "unexpected", reason: firstLine };
}

/**
 * Last-resort net.
 *
 * A rejected promise nobody awaited would otherwise end the process with a raw
 * stack trace: no receipt, and no indication of which kind of failure it was.
 * Report it as inconclusive instead, because a run that could not complete must
 * never be mistaken for a run that found data leaving the device.
 */
process.on("unhandledRejection", (reason) => {
  console.error(
    "Privacy-proof capture INCONCLUSIVE — a background operation rejected, so " +
      "this run proves nothing in either direction. This is NOT a finding " +
      "about the site:",
  );
  console.error(reason);
  void activeBrowser?.close().catch(() => {});
  process.exit(1);
});

async function main() {
  const browser = await chromium.launch({ headless: true });
  activeBrowser = browser;
  const browserVersion = browser.version();

  const scenarios = [];
  // Scenarios that could not be completed. These are NOT findings about the
  // site: they mean this run proves nothing about that scenario either way.
  const unavailable = [];
  for (const capture of [
    captureImageConversion,
    captureHeicConversion,
    captureOcrRun,
    capturePdfRotation,
  ]) {
    process.stdout.write(`[privacy-proof] ${capture.name} ... `);
    try {
      const scenario = await capture(browser);
      scenarios.push(scenario);
      console.log(
        `${scenario.totalRequests} requests, ` +
          `${scenario.uploadRequests} uploads, ` +
          `${scenario.canaryLeaks} canary leaks`,
      );
    } catch (error) {
      const classified = classifyScenarioError(error);
      unavailable.push({ scenario: capture.name, ...classified });
      console.log(`could not complete (${classified.errorClass})`);
    }
  }

  const userAgent = await (
    await browser.newContext()
  )
    .newPage()
    .then(async (page) => {
      const ua = await page.evaluate(() => navigator.userAgent);
      await page.context().close();
      return ua;
    });
  await browser.close();

  // The evidence only counts when nothing left the device.
  const violations = [];
  for (const scenario of scenarios) {
    if (scenario.uploadRequests !== 0) {
      violations.push(
        `${scenario.id}: ${scenario.uploadRequests} upload requests`,
      );
    }
    if (scenario.canaryLeaks !== 0) {
      violations.push(`${scenario.id}: ${scenario.canaryLeaks} canary leaks`);
    }
    if (scenario.unexpectedCrossOriginRequests !== 0) {
      violations.push(
        `${scenario.id}: ${scenario.unexpectedCrossOriginRequests} unexpected ` +
          `cross-origin requests (${scenario.unexpectedHosts.join(", ")})`,
      );
    }
  }
  if (scenarios.some((scenario) => scenario.recognizedTextMatches === false)) {
    violations.push("ocr-language-pack: recognized text mismatch");
  }
  const heicScenario = scenarios.find(
    (scenario) => scenario.id === "image-tool-heic-convert",
  );
  if (heicScenario && heicScenario.decoderAssets.sameOriginOnly !== true) {
    violations.push(
      "image-tool-heic-convert: HEIC decoder assets were not same-origin-only",
    );
  }
  const ocrScenario = scenarios.find(
    (scenario) => scenario.id === "ocr-language-pack",
  );
  if (ocrScenario) {
    if (
      ocrScenario.languagePack.uploadRequests !== 0 ||
      ocrScenario.languagePack.crossOriginRequests !== 0
    ) {
      violations.push(
        "ocr-language-pack: language pack download was not same-origin-only",
      );
    }
    if (
      ocrScenario.multiLanguage.uploadRequests !== 0 ||
      ocrScenario.multiLanguage.crossOriginRequests !== 0
    ) {
      violations.push(
        "ocr-language-pack: multi-language measured run left the origin",
      );
    }
    if (ocrScenario.multiLanguage.recognizedTextMatches === false) {
      violations.push("ocr-language-pack: Chinese recognized text mismatch");
    }
  }
  if (violations.length > 0) {
    console.error(
      "Privacy-proof capture FAILED — a boundary was crossed:\n" +
        violations.map((violation) => `- ${violation}`).join("\n"),
    );
    for (const scenario of scenarios) {
      if (scenario.thirdPartyHosts.length > 0) {
        console.error(
          `${scenario.id} third-party hosts: ${scenario.thirdPartyHosts.join(", ")}`,
        );
        for (const request of scenario.requests) {
          if (!request.sameOrigin) {
            console.error(
              `  ${request.method} ${request.host}${request.path.slice(0, 120)} (${request.resourceType})`,
            );
          }
        }
      }
    }
    process.exitCode = 1;
  }

  // A run that could not complete is reported separately. It still exits
  // non-zero, but it must not read as evidence that data left the device.
  if (unavailable.length > 0) {
    console.error(
      `Privacy-proof capture INCONCLUSIVE — ${unavailable.length} of 4 ` +
        "scenarios could not be completed, so this run proves nothing about " +
        "them in either direction. This is NOT a finding about the site:\n" +
        unavailable
          .map(
            (entry) =>
              `- ${entry.scenario} (${entry.errorClass}): ${entry.reason}`,
          )
          .join("\n"),
    );
    process.exitCode = 1;
  }

  const outcome =
    violations.length > 0
      ? unavailable.length > 0
        ? "violation+inconclusive"
        : "violation"
      : unavailable.length > 0
        ? "inconclusive"
        : "verified";

  const payload = {
    schemaVersion: 1,
    capturedAt: new Date().toISOString().slice(0, 10),
    environment: {
      description:
        "Headless Chromium against the public site over the network, recording every request (including dedicated Web Worker fetches); service workers blocked, so repeat asset loads are served by the browser's HTTP cache and produce zero recorded requests. The site shell's own analytics request is outside the measured windows; this harness measures tool workspaces.",
      browser: `Chromium ${browserVersion} (headless)`,
      userAgent,
      os: `${platform()} ${process.arch}`,
      cpu: cpus()[0]?.model ?? "unknown",
      node: process.version,
      baseUrl,
    },
    harness: {
      script: "evidence-harness/capture-privacy-proof.mjs",
      trace: createHash("sha256")
        .update(readFileSync(fileURLToPath(import.meta.url)))
        .digest("hex"),
    },
    // `verified` means every scenario completed and nothing left the device.
    // Any other outcome exits non-zero. `inconclusive` is deliberately distinct
    // from `violation`: a transport failure is not evidence of a data leak.
    outcome,
    violations,
    unavailable,
    scenarios,
  };

  const resolvedOut = outPath.startsWith("/")
    ? outPath
    : `${projectRoot}${outPath}`;
  mkdirSync(resolvedOut.slice(0, resolvedOut.lastIndexOf("/")), {
    recursive: true,
  });
  writeFileSync(resolvedOut, `${JSON.stringify(payload, null, 2)}\n`);
  console.log(`[privacy-proof] wrote ${resolvedOut}`);
  if (process.exitCode === 1) process.exit(1);
}

main().catch(async (error) => {
  console.error(error);
  await activeBrowser?.close().catch(() => {});
  // Exit explicitly: a failed run must fail loudly, not hang.
  process.exit(1);
});
