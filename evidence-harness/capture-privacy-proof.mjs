/**
 * Toolars privacy-proof capture harness.
 *
 * Re-runnable evidence producer for the /privacy-proof "verify it yourself"
 * section. For three representative scenarios — an image conversion, the
 * local OCR engine, and a PDF rotation — it drives the real tool workspaces
 * in headless Chromium while recording every network request through the
 * CDP Network domain:
 *
 *   - image-format-converter: a full PNG → JPEG conversion plus download,
 *     with a canary marker embedded in a PNG tEXt chunk; any request that
 *     carried the marker off-device fails the run.
 *   - image-format-converter (HEIC input): a HEIC → JPEG conversion whose
 *     lazy libheif decoder (~3.3 MB) may only ever be fetched from the
 *     site's own origin; the measured canary run must issue zero requests,
 *     proving the decoder is cached and the photo never uploaded.
 *   - image-to-text-ocr: the OCR engine, worker, and the English and
 *     Simplified Chinese language packs must arrive exclusively from the
 *     site's own origin; the measured (post-warm-up) runs must issue zero
 *     requests.
 *   - pdf-rotator: sample load plus rotate plus download with zero uploads.
 *
 * The script writes a dated summary (request counts, origins, and the
 * measured-window request log — paths and methods only, never content) to
 * src/data/privacy-proof/capture-summaries.json, which the privacy-proof
 * page renders as evidence cards. Re-run after any runtime change and
 * commit the refreshed JSON to update the published evidence.
 *
 * Usage:
 *   node capture-privacy-proof.mjs
 *   node capture-privacy-proof.mjs --base-url http://127.0.0.1:9608
 *   node capture-privacy-proof.mjs --out /tmp/receipt.json
 *
 * Defaults: BASE_URL https://toolars.com; the receipt is written to
 * ./privacy-proof-receipt.json relative to the working directory.
 *
 * This file is generated by scripts/export-open-source.mjs. Only the target
 * URL, the output path, the fixture path and the receipt metadata differ from
 * the internal capture script; the scenario-driving logic is unchanged, so an
 * external run measures the same behaviour as the project's own capture.
 */

