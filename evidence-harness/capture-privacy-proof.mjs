/**
 * Hosts the site shell itself contacts. These are disclosed on /privacy-proof
 * and enumerated in src/data/privacy-proof/external-services.ts. A measured
 * scenario window is about what the TOOL does with your file, so a request to a
 * disclosed shell host is reported but is not by itself a failure. Uploads and
 * canary leaks stay fatal regardless of host.
 */
const DISCLOSED_SHELL_HOSTS = new Set(["track.toolars.com"]);

const KiB = 1024;

/**
 * One scenario's request log: metadata only, never bodies. Uses Playwright
 * request events (not a page-scoped CDP session) because dedicated Web
 * Workers — the OCR engine, PDF runtime — issue their fetches from a
 * separate target that a page CDP session would miss.
 */
function attachNetworkRecorder(page, canary) {
  const requests = [];
  let sequence = 0;

  page.on("request", (request) => {
    const url = request.url();
    // Blob/data object URLs are local references created by the page
    // itself; no bytes cross the network for them.
    if (/^(?:blob|data|about):/u.test(url)) return;

    let host = "";
    let path = url;
    try {
      const parsed = new URL(url);
      host = parsed.host;
      path = `${parsed.pathname}${parsed.search}`;
    } catch {
      path = url;
    }
    const postData = request.postData();
    sequence += 1;
    requests.push({
      seq: sequence,
      method: request.method(),
      host,
      path,
      resourceType: request.resourceType(),
      sameOrigin: url.startsWith(baseOrigin),
      hasPostData: postData !== null,
      carriedCanary:
        url.includes(canary) || postData?.includes(canary) === true,
    });
  });

  return requests;
}

function summarize(requests) {
  const thirdPartyHosts = [
    ...new Set(
      requests
        .filter((request) => !request.sameOrigin)
        .map((request) => request.host),
    ),
  ].sort();
  const crossOrigin = requests.filter((request) => !request.sameOrigin);
  const unexpected = crossOrigin.filter(
    (request) => !DISCLOSED_SHELL_HOSTS.has(request.host),
  );
  return {
    totalRequests: requests.length,
    sameOriginRequests: requests.filter((request) => request.sameOrigin).length,
    crossOriginRequests: crossOrigin.length,
    disclosedShellRequests: crossOrigin.length - unexpected.length,
    unexpectedCrossOriginRequests: unexpected.length,
    unexpectedHosts: [
      ...new Set(unexpected.map((request) => request.host)),
    ].sort(),
    uploadRequests: requests.filter(
      (request) =>
        request.hasPostData ||
        !["GET", "HEAD", "OPTIONS"].includes(request.method),
    ).length,
    canaryLeaks: requests.filter((request) => request.carriedCanary).length,
    thirdPartyHosts,
  };
}

async function waitForRuntime(page) {
  await page.locator('[data-runtime-ready="true"]').waitFor({
    state: "attached",
    timeout: 30_000,
  });
}

async function waitForFileInput(page) {
  await page.locator('input[type="file"]').waitFor({ state: "attached" });
  await page.waitForFunction(
    () => {
      const input = document.querySelector('input[type="file"]');
      return input instanceof HTMLInputElement && !input.disabled;
    },
    { timeout: 30_000 },
  );
}

async function waitForStatusCompleted(page, timeoutMs = 60_000) {
  await page.waitForFunction(
    () => {
      const status = document.querySelector(
        'section[aria-labelledby] p[aria-live="polite"]',
      );
      return status?.textContent?.includes("completed") === true;
    },
    { timeout: timeoutMs },
  );
}

async function downloadResult(page, buttonName) {
  const [download] = await Promise.all([
    page.waitForEvent("download", { timeout: 30_000 }),
    page.getByRole("button", { name: buttonName, exact: true }).click(),
  ]);
  const path = await download.path();
  await download.delete();
  return { suggestedFilename: download.suggestedFilename(), path };
}

/** Scenario 1: image-format-converter, warm-up run + measured canary run. */
async function captureImageConversion(browser) {
  const canary = `tlrs-proof-${Math.random().toString(36).slice(2, 12)}`;
  const context = await browser.newContext({ serviceWorkers: "block" });
  const page = await context.newPage();
  const requests = attachNetworkRecorder(page, canary);

  await page.goto(`${baseUrl}/tools/image-format-converter`, {
    // Deliberately NOT "networkidle": the live site loads a cookieless
    // analytics script from a first-party proxy, so network idleness depends on
    // third-party infrastructure and on whether the operator blocks it. A
    // verifier who blocks that host would time out and read a false failure.
    // Readiness is established by the explicit workspace waits below instead.
    waitUntil: "domcontentloaded",
  });
  await waitForRuntime(page);
  await waitForFileInput(page);

  // Warm-up: full conversion so every lazy chunk and worker is loaded.
  await page.locator('input[type="file"]').setInputFiles({
    name: "proof-warmup.png",
    mimeType: "image/png",
    buffer: makeSizedNoisePng(256 * KiB),
  });
  await page.getByRole("radio", { name: /JPEG — smaller files/u }).check();
  await page
    .getByRole("button", { name: "Convert image", exact: true })
    .click();
  await waitForStatusCompleted(page);
  await page.getByRole("button", { name: "Download", exact: true }).click();
  await page.waitForTimeout(500);

  // Measured window: fresh conversion of a canary-tagged file + download.
  requests.length = 0;
  await page.locator('input[type="file"]').setInputFiles({
    name: `proof-${canary}.png`,
    mimeType: "image/png",
    buffer: makeSizedNoisePng(256 * KiB, canary),
  });
  await page.getByRole("radio", { name: /JPEG — smaller files/u }).check();
  await page
    .getByRole("button", { name: "Convert image", exact: true })
    .click();
  await waitForStatusCompleted(page);
  const download = await downloadResult(page, "Download");

  const summary = summarize(requests);
  await context.close();
  return {
    id: "image-tool-convert",
    toolSlug: "image-format-converter",
    window:
      "One full conversion plus download, after page and runtime warm-up.",
    canary,
    outputFile: download.suggestedFilename,
    ...summary,
    requests: [...requests],
  };
}

/** Scenario 2: HEIC input — lazy decoder same-origin only, zero-upload flow. */
async function captureHeicConversion(browser) {
  const canary = `tlrs-proof-${Math.random().toString(36).slice(2, 12)}`;
  const context = await browser.newContext({ serviceWorkers: "block" });
  const page = await context.newPage();
  const requests = attachNetworkRecorder(page, canary);
  const heicFixture = readFileSync(
    `${harnessRoot}fixtures/heic/gradient-96x64.heic`,
  );

  await page.goto(`${baseUrl}/tools/image-format-converter`, {
    // Deliberately NOT "networkidle": the live site loads a cookieless
    // analytics script from a first-party proxy, so network idleness depends on
    // third-party infrastructure and on whether the operator blocks it. A
    // verifier who blocks that host would time out and read a false failure.
    // Readiness is established by the explicit workspace waits below instead.
    waitUntil: "domcontentloaded",
  });
  await waitForRuntime(page);
  await waitForFileInput(page);

  const heicAssetRequests = [];
  page.on("request", (request) => {
    if (
      /\/generated\/(?:runtime\/[a-f0-9]+\/)?(?:libheif|heic-decode)/u.test(
        new URL(request.url()).pathname,
      )
    ) {
      heicAssetRequests.push({
        path: new URL(request.url()).pathname,
        sameOrigin: request.url().startsWith(baseOrigin),
      });
    }
  });

  // Warm-up: the first HEIC conversion downloads the lazy libheif decoder.
  await page.locator('input[type="file"]').setInputFiles({
    name: "proof-warmup.heic",
    mimeType: "image/heic",
    buffer: heicFixture,
  });
  await page.getByRole("radio", { name: /JPEG — smaller files/u }).check();
  await page
    .getByRole("button", { name: "Convert image", exact: true })
    .click();
  await waitForStatusCompleted(page, 90_000);
  await page.getByRole("button", { name: "Download", exact: true }).click();
  await page.waitForTimeout(500);

  // Measured window: the decoder is cached now, so a fresh conversion of a
  // canary-named HEIC must issue zero requests.
  requests.length = 0;
  await page.locator('input[type="file"]').setInputFiles({
    name: `proof-${canary}.heic`,
    mimeType: "image/heic",
    buffer: heicFixture,
  });
  await page.getByRole("radio", { name: /JPEG — smaller files/u }).check();
  await page
    .getByRole("button", { name: "Convert image", exact: true })
    .click();
  await waitForStatusCompleted(page, 90_000);
  const download = await downloadResult(page, "Download");

  const measuredSummary = summarize(requests);
  await context.close();
  return {
    id: "image-tool-heic-convert",
    toolSlug: "image-format-converter",
    window:
      "Second HEIC → JPEG conversion plus download, after the lazy decoder warm-up fetch.",
    canary,
    outputFile: download.suggestedFilename,
    ...measuredSummary,
    decoderAssets: {
      window: "First HEIC conversion: the lazy libheif decoder download.",
      sameOriginOnly:
        heicAssetRequests.length > 0 &&
        heicAssetRequests.every((request) => request.sameOrigin),
      paths: [...new Set(heicAssetRequests.map((request) => request.path))],
    },
    requests: [...requests],
  };
}

/** Scenario 3: local OCR — engine and language packs same-origin only. */
async function captureOcrRun(browser) {
  const canary = `tlrs-proof-${Math.random().toString(36).slice(2, 12)}`;
  const context = await browser.newContext({ serviceWorkers: "block" });
  const page = await context.newPage();
  const requests = attachNetworkRecorder(page, canary);

  await page.goto(`${baseUrl}/tools/image-to-text-ocr`, {
    // Deliberately NOT "networkidle": the live site loads a cookieless
    // analytics script from a first-party proxy, so network idleness depends on
    // third-party infrastructure and on whether the operator blocks it. A
    // verifier who blocks that host would time out and read a false failure.
    // Readiness is established by the explicit workspace waits below instead.
    waitUntil: "domcontentloaded",
  });
  await page
    .getByRole("button", { name: "Choose an image", exact: true })
    .waitFor({ timeout: 30_000 });

  // Rendered text images produced by the page's own canvas: one English,
  // one Simplified Chinese sample.
  const [imageBase64, chineseImageBase64] = await page.evaluate(() => {
    const render = (text) => {
      const canvas = document.createElement("canvas");
      canvas.width = 1000;
      canvas.height = 220;
      const context = canvas.getContext("2d");
      if (!context) throw new Error("Canvas 2D context unavailable.");
      context.fillStyle = "white";
      context.fillRect(0, 0, 1000, 220);
      context.fillStyle = "black";
      context.font = "64px Arial";
      context.fillText(text, 50, 130);
      return canvas.toDataURL().split(",")[1];
    };
    return [render("TOOLARS LOCAL OCR"), render("本地识别 隐私无忧")];
  });

  const ocrAssetRequests = [];
  async function runOnce(label, sampleBase64) {
    const before = requests.length;
    // Promise.all attaches a handler to both immediately. Creating the waiter
    // and awaiting the click first leaves the waiter floating: if the click
    // throws, the waiter's later rejection is unhandled and kills the process.
    const [chooser] = await Promise.all([
      page.waitForEvent("filechooser"),
      page
        .getByRole("button", { name: "Choose an image", exact: true })
        .click(),
    ]);
    await chooser.setFiles({
      name: `proof-${label}-${canary}.png`,
      mimeType: "image/png",
      buffer: Buffer.from(sampleBase64, "base64"),
    });
    await page
      .getByRole("button", { name: "Recognize text", exact: true })
      .click();
    await page
      .getByLabel("Recognized text", { exact: true })
      .waitFor({ timeout: 60_000 });
    const value = await page
      .getByLabel("Recognized text", { exact: true })
      .inputValue();
    const windowRequests = requests.slice(before);
    ocrAssetRequests.push(
      ...windowRequests
        .filter(
          (request) =>
            request.sameOrigin && /\/(?:ocr|generated)\//u.test(request.path),
        )
        .map((request) => request.path),
    );
    return value;
  }

  const warmUpText = await runOnce("warmup", imageBase64);
  const measuredBefore = requests.length;
  const measuredText = await runOnce("measured", imageBase64);
  const measuredWindow = requests.slice(measuredBefore);

  // Multi-language pass: selecting Simplified Chinese downloads its
  // language pack once — it must come from this origin only — and a warmed
  // Chinese recognition run must issue zero requests.
  const packBefore = requests.length;
  await page
    .getByLabel("Recognition language", { exact: true })
    .selectOption("chi_sim");
  await page
    .getByText("Simplified Chinese downloaded — available offline.", {
      exact: true,
    })
    .waitFor({ timeout: 60_000 });
  const packWindow = requests.slice(packBefore);
  const packSummary = summarize(packWindow);

  const chiWarmText = await runOnce("chi-warmup", chineseImageBase64);
  const chiMeasuredBefore = requests.length;
  const chiMeasuredText = await runOnce("chi-measured", chineseImageBase64);
  const chiMeasuredWindow = requests.slice(chiMeasuredBefore);

  const summary = summarize(measuredWindow);
  await context.close();
  return {
    id: "ocr-language-pack",
    toolSlug: "image-to-text-ocr",
    window:
      "Second recognition pass, after the engine and language pack warm-up fetch.",
    recognizedTextMatches:
      warmUpText === measuredText && measuredText.length > 0,
    ...summary,
    languagePack: {
      language: "chi_sim",
      window:
        "Selecting Simplified Chinese downloads its language pack once, then stays cached.",
      ...packSummary,
      sameOriginAssetPaths: [
        ...new Set(
          packWindow
            .filter(
              (request) =>
                request.sameOrigin && /\/generated\//u.test(request.path),
            )
            .map((request) => request.path),
        ),
      ].sort(),
    },
    multiLanguage: {
      language: "chi_sim",
      window:
        "Second Simplified Chinese recognition pass, after the pack download.",
      recognizedTextMatches:
        chiWarmText === chiMeasuredText && /[一-鿿]/u.test(chiMeasuredText),
      ...summarize(chiMeasuredWindow),
    },
    sameOriginAssetPaths: [...new Set(ocrAssetRequests)].sort(),
    requests: measuredWindow,
  };
}

